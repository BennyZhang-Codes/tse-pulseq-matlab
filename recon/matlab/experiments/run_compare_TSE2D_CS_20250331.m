%% Reconstruct and compare the 2025-03-31 fully sampled/CS TSE series
% Outputs include geometry-preserving NIfTI volumes, aligned volumes,
% absolute-error volumes, NRMSE/SSIM tables, and a 600-dpi paper figure.

clearvars;

experimentDir = fileparts(mfilename('fullpath'));
matlabDir = fileparts(experimentDir);
repoRoot = fileparts(fileparts(matlabDir));
addpath(matlabDir,fullfile(matlabDir,'utils'),experimentDir);
baseDir = fullfile(repoRoot,'Recon_dev','CS_Recon','20250331_CS');
datDir = fullfile(baseDir,'dat');
outputDir = fullfile(baseDir,'out');
mapVBVDPath = 'E:\Tools\mapVBVD';

tvWeight = 0.006;
waveletWeight = 0.0005;
maximumIterations = 350;
if ~isfolder(outputDir)
    mkdir(outputDir);
end

referenceFile = fullfile(datDir, ...
    'meas_MID00037_FID66796_TSE_0p47_256_r1_nRef0_sli5.dat');
acceleratedFiles = {
    'meas_MID00038_FID66797_CSTSE_0p47_256_r2_nRef26_sli5.dat'
    'meas_MID00039_FID66798_CSTSE_0p47_256_r3_nRef26_sli5.dat'
    'meas_MID00040_FID66799_CSTSE_0p47_256_r4_nRef26_sli5.dat'
    'meas_MID00041_FID66800_CSTSE_0p47_256_r5_nRef26_sli5.dat'};

commonArguments = {'MapVBVDPath',mapVBVDPath, ...
    'Prewhiten',true,'PhaseCorrection',false, ...
    'EchoMagnitudeCorrection',false,'Slices',1:5, ...
    'SaveMat',false,'SaveFigures',false,'SaveNifti',true, ...
    'OverwriteOutputs',true,'Verbose',true};

%% Fully sampled reference: matched ESPIRiT-SENSE plus conventional RSS
referenceSense = recon_TSE2D(referenceFile,commonArguments{:}, ...
    'ReconstructionMethod','sense','SENSEIterations',50, ...
    'SENSETolerance',1e-6,'SENSETikhonov',0, ...
    'OutputDir',outputDir,'OutputPrefix','TSE_R1_ESPIRiT_SENSE');
referenceRSS = recon_TSE2D(referenceFile,commonArguments{:}, ...
    'ReconstructionMethod','rss','OutputDir',outputDir, ...
    'OutputPrefix','TSE_R1_RSS');
reference = struct('sense',single(referenceSense.images.reconstructed), ...
    'rss',single(referenceRSS.images.reconstructed), ...
    'meta',referenceSense.meta,'senseInfo',{referenceSense.sense}, ...
    'senseOutputFiles',referenceSense.outputFiles, ...
    'rssOutputFiles',referenceRSS.outputFiles);
save(fullfile(outputDir,'TSE_R1_reference_compact.mat'), ...
    'reference','-v7.3');

%% Accelerated CS reconstructions and reference comparisons
summaries = cell(4,1);
sliceTables = cell(4,1);
comparisons = cell(4,1);
compactResults = cell(4,1);
for index = 1:4
    acceleration = index+1;
    prefix = sprintf('CS_R%d_ESPIRiT_TV0p006_W0p0005',acceleration);
    result = recon_TSE2D(fullfile(datDir,acceleratedFiles{index}), ...
        commonArguments{:},'ReconstructionMethod','cs', ...
        'CSIterations',maximumIterations,'CSTVWeight',tvWeight, ...
        'CSWaveletWeight',waveletWeight,'CSWaveletLevels',2, ...
        'IterativeUseGPU',false,'KeepKspace',false, ...
        'KeepSensitivityMaps',false,'OutputDir',outputDir, ...
        'OutputPrefix',prefix);

    comparison = evaluate_TSE2D_reconstruction( ...
        result.images.reconstructed,reference.sense, ...
        'Register',true,'MaximumTranslationPixels',4);
    comparisons{index} = comparison;
    alignedNifti = write_TSE2D_nifti( ...
        comparison.reconstructedAligned,reference.meta,outputDir, ...
        'Prefix',[prefix '_AlignedToR1'], ...
        'Description',sprintf('CS TSE R%d aligned to full R1',acceleration), ...
        'Overwrite',true);
    errorNifti = write_TSE2D_nifti( ...
        comparison.absoluteError,reference.meta,outputDir, ...
        'Prefix',[prefix '_AbsErrorVsR1'], ...
        'Description',sprintf('Absolute normalized CS R%d error',acceleration), ...
        'Overwrite',true);

    dataResidual = mean(cellfun( ...
        @(x) x.finalRelativeDataResidual,result.cs));
    iterations = max(cellfun(@(x) x.iterations,result.cs));
    summaries{index} = table(acceleration,tvWeight,waveletWeight, ...
        iterations,dataResidual,comparison.nrmse,comparison.ssim, ...
        comparison.psnr,comparison.intensityScale, ...
        string(result.outputFiles.nifti),string(alignedNifti), ...
        string(errorNifti),'VariableNames',{'R','TVWeight', ...
        'WaveletWeight','Iterations','DataResidual','NRMSE','SSIM', ...
        'PSNR','IntensityScale','Nifti','AlignedNifti','ErrorNifti'});
    sliceTable = comparison.sliceMetrics;
    sliceTable.R = repmat(acceleration,height(sliceTable),1);
    sliceTable.TVWeight = repmat(tvWeight,height(sliceTable),1);
    sliceTable.WaveletWeight = repmat(waveletWeight,height(sliceTable),1);
    sliceTables{index} = movevars(sliceTable, ...
        {'R','TVWeight','WaveletWeight'},'Before',1);
    compactResults{index} = struct('R',acceleration, ...
        'sourceFile',string(acceleratedFiles{index}), ...
        'images',single(result.images.reconstructed),'meta',result.meta, ...
        'csInfo',{result.cs},'outputFiles',result.outputFiles, ...
        'comparison',comparison);
end

summary = vertcat(summaries{:});
sliceMetrics = vertcat(sliceTables{:});
writetable(summary,fullfile(outputDir,'CS_vs_full_TSE_metrics.csv'));
writetable(sliceMetrics, ...
    fullfile(outputDir,'CS_vs_full_TSE_slice_metrics.csv'));
save(fullfile(outputDir,'CS_vs_full_TSE_comparison.mat'), ...
    'reference','compactResults','comparisons','summary', ...
    'sliceMetrics','-v7.3');

figureFiles = create_TSE2D_CS_comparison_figure( ...
    comparisons,summary,outputDir,'SliceIndex',3, ...
    'Prefix','Figure_CS_vs_fully_sampled_TSE','DPI',600);
disp(summary(:,{'R','NRMSE','SSIM','PSNR','DataResidual'}));
disp(figureFiles);
